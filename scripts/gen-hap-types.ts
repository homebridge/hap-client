import type { PluginType } from './plugin-types.ts'

import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { Access, Categories, Characteristic, Formats, Perms, Service, Units } from '@homebridge/hap-nodejs'

import { PluginCharacteristics, PluginServices } from './plugin-types.ts'

const __dirname = dirname(fileURLToPath(import.meta.url))

const UUID_REGEX = /^[0-9A-F]{8}-[0-9A-F]{4}-[1-5][0-9A-F]{3}-[89AB][0-9A-F]{3}-[0-9A-F]{12}$/

/**
 * Merges the hand-maintained plugin types into the generated maps, after the
 * hap-nodejs and homebridge-lib types have claimed their names and UUIDs.
 *
 * A collision is an error rather than a silent skip: half-registering an entry
 * (one direction emitted, the other already taken) would look like it worked
 * while behaving differently to every other type. The usual cause is a plugin
 * type that has since been adopted upstream, and the fix is to delete the entry.
 */
function mergePluginTypes(lines: string[], uuids: Set<unknown>, names: Set<unknown>, entries: PluginType[], kind: string) {
  for (const { name, uuid: rawUuid, definedBy } of entries) {
    const uuid = rawUuid.toUpperCase()
    if (!UUID_REGEX.test(uuid)) {
      throw new Error(`Plugin ${kind} '${name}' (${definedBy}) has an invalid UUID: '${rawUuid}'`)
    }
    if (uuids.has(uuid) || names.has(name)) {
      throw new Error(
        `Plugin ${kind} '${name}' (${definedBy}) collides with an existing ${kind} name or UUID - `
        + `if the type is now provided by hap-nodejs or homebridge-lib, remove it from scripts/plugin-types.ts`,
      )
    }
    lines.push(`  '${uuid}': '${name}',`)
    lines.push(`  '${name}': '${uuid}',`)
    uuids.add(uuid)
    names.add(name)
  }
}

// @ts-expect-error - TS7016
const { EveHomeKitTypes } = await import('homebridge-lib/EveHomeKitTypes')
// @ts-expect-error - TS7016
const { MyHomeKitTypes } = await import('homebridge-lib/MyHomeKitTypes')

const homebridge = {
  hap: {
    Access,
    Categories,
    Characteristic,
    Formats,
    Perms,
    Service,
    Units,
  },
}

const customTypes = [
  new EveHomeKitTypes(homebridge),
  new MyHomeKitTypes(homebridge),
]

/** Generate Service Types */

let Services = [
  'export const Services = {',
] as any

const serviceUUIDs = new Set()
const serviceNames = new Set()
const serviceEntries = [
  ...Object.entries(Service),
  ...customTypes.flatMap(customType => Object.entries(customType.Services)),
]

for (const [name, value] of serviceEntries) {
  if (value.UUID) {
    if (!serviceUUIDs.has(value.UUID)) {
      Services.push(`  '${value.UUID}': '${name}',`)
      serviceUUIDs.add(value.UUID)
    }
    if (!serviceNames.has(name)) {
      Services.push(`  '${name}': '${value.UUID}',`)
      serviceNames.add(name)
    }
  }
}

mergePluginTypes(Services, serviceUUIDs, serviceNames, PluginServices, 'service')

Services.push(`}\n\n`)
Services = Services.join('\n')

/** Generate Characteristic Types */

let Characteristics = [
  'export const Characteristics = {',
] as any

const characteristicEntries = [
  ...Object.entries(Characteristic),
  ...customTypes.flatMap(customType => Object.entries(customType.Characteristics)),
]

const characteristicUUIDs = new Set()
const characteristicNames = new Set()

for (const [name, value] of characteristicEntries) {
  if (value.UUID) {
    if (!characteristicUUIDs.has(value.UUID)) {
      Characteristics.push(`  '${value.UUID}': '${name}',`)
      characteristicUUIDs.add(value.UUID)
    }
    if (!characteristicNames.has(name)) {
      Characteristics.push(`  '${name}': '${value.UUID}',`)
      characteristicNames.add(name)
    }
  }
}

mergePluginTypes(Characteristics, characteristicUUIDs, characteristicNames, PluginCharacteristics, 'characteristic')

Characteristics.push(`}\n\n`)
Characteristics = Characteristics.join('\n')

/** Generate Category Types */

let Category = [
  'export const Categories = {',
] as any

// @ts-expect-error - TS2475
for (const [name, value] of Object.entries(Categories)) {
  if (typeof value === 'number') {
    Category.push(`  ${name}: ${value},`)
  }
}

Category.push(`}\n\n`)
Category = Category.join('\n')

let Enums = [
  'export const Enums = {',
] as any

for (const [name, value] of Object.entries(Characteristic)) {
  if (typeof value === 'function' && value.prototype) {
    const staticKeys = Object.getOwnPropertyNames(value)
      .filter(
        key =>
          key !== 'length'
          && key !== 'name'
          && key !== 'prototype'
          && key !== 'UUID'
          && typeof (value as any)[key] !== 'function',
      )
    if (staticKeys.length > 0) {
      Enums.push(`  ${name}: {`)
      staticKeys.forEach((k) => {
        Enums.push(`    ${(value as any)[k]}: '${k}',`)
      })
      Enums.push('  },')
    }
  }
}
Enums.push(`}\n`)
Enums = Enums.join('\n')

const out = `/* This file is automatically generated */\n\n${Services}${Characteristics}${Category}${Enums}`

writeFileSync(resolve(__dirname, '../src/hap-types.ts'), out, 'utf8')
